"""Copy the parts of the brand kit the app needs into frontend/src/brand.

The frontend must build on its own (no imports from outside frontend/), so this step writes a
self-contained copy: tokens, icon paths, logo and illustration artwork, the leaf vein, the
contour tile, and subset web fonts. Run after the other generators:

    python3 brand/tools/build_frontend.py

Everything in frontend/src/brand is generated. Change the kit, not the copy.
"""
from __future__ import annotations

import json
import os
import re
import shutil

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
BRAND = os.path.normpath(os.path.join(HERE, ".."))
FRONT = os.path.normpath(os.path.join(BRAND, "..", "frontend"))
OUT = os.path.join(FRONT, "src", "brand")
NOTE = "Generated by brand/tools/build_frontend.py. Do not edit by hand."

# Latin text, punctuation, currency and the few symbols the product uses
UNICODES = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x2010, 0x2028))
            + [0x2030, 0x2032, 0x2033, 0x2039, 0x203A, 0x20AC, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2022, 0x2026])
FONTS = [("Fraunces-SemiBold.ttf", "fraunces-600"), ("Fraunces-Regular.ttf", "fraunces-400"),
         ("Manrope-ExtraBold.ttf", "manrope-800"), ("Manrope-Bold.ttf", "manrope-700"),
         ("SourceSans3-Regular.ttf", "source-sans-3-400"), ("SourceSans3-Semibold.ttf", "source-sans-3-600")]


def read(*parts):
    return open(os.path.join(BRAND, *parts)).read()


def svg_parts(text):
    """(viewBox, inner markup without title/desc) of an SVG file."""
    vb = re.search(r'viewBox="([^"]+)"', text).group(1)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
    return vb, re.sub(r"<title>.*?</title>|<desc>.*?</desc>", "", inner, flags=re.S).strip()


def path_of(text):
    return re.search(r' d="([^"]+)"', text).group(1)


def fonts():
    dst = os.path.join(OUT, "fonts")
    os.makedirs(dst, exist_ok=True)
    total = 0
    for src, name in FONTS:
        font = TTFont(os.path.join(BRAND, "fonts", src))
        opts = subset.Options()
        opts.layout_features = ["*"]
        opts.name_IDs = [1, 2, 4, 6]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        font.flavor = "woff"
        path = os.path.join(dst, name + ".woff")
        font.save(path)
        total += os.path.getsize(path)
    for lic in ("Fraunces-LICENSE.txt", "Manrope-LICENSE.txt", "SourceSans3-LICENSE.md"):
        shutil.copy(os.path.join(BRAND, "fonts", lic), os.path.join(dst, lic))
    print(f"fonts: {len(FONTS)} subset WOFF files, {total / 1024:.0f} KB")


def main():
    os.makedirs(OUT, exist_ok=True)
    # tokens and icons, as they are
    open(os.path.join(OUT, "tokens.css"), "w").write(read("tokens", "nexus-tokens.css").replace(
        "Do not edit by hand. */", "Do not edit by hand. */\n/* Copied into the app by brand/tools/build_frontend.py. */"))
    open(os.path.join(OUT, "icons.ts"), "w").write(read("icons", "nexus-icons.ts"))

    # logo, illustration and pattern artwork as data the components draw
    sym_vb, _ = svg_parts(read("logo", "masters", "nexus-symbol-convergence.svg"))
    word = read("logo", "masters", "nexus-wordmark.svg")
    scenes = {}
    for name in ("clear-day", "first-shoot", "waymark", "record"):
        vb, inner = svg_parts(read("illustrations", f"nexus-scene-{name}.svg"))
        scenes[name] = inner
    contour_vb, contour = svg_parts(read("patterns", "nexus-pattern-contour.svg"))
    art = {
        "symbol": {"viewBox": sym_vb, "d": path_of(read("logo", "masters", "nexus-symbol-convergence.svg"))},
        "symbolSmall": {"viewBox": sym_vb, "d": path_of(read("logo", "masters", "nexus-symbol-convergence-small.svg"))},
        "wordmark": {"viewBox": re.search(r'viewBox="([^"]+)"', word).group(1), "d": path_of(word)},
        "sceneViewBox": "0 0 480 320",
        "scenes": scenes,
        "contour": {"size": float(contour_vb.split()[2]), "markup": contour},
    }
    with open(os.path.join(OUT, "art.ts"), "w") as f:
        f.write(f"// {NOTE}\n// Logo, illustration and pattern artwork from the Nexus brand kit.\n"
                "export const nexusArt = " + json.dumps(art, indent=1) + " as const;\n\n"
                "export type NexusSceneName = keyof typeof nexusArt.scenes;\n")
    shutil.copy(os.path.join(BRAND, "patterns", "nexus-leaf-vein.svg"), os.path.join(OUT, "leaf-vein.svg"))
    fonts()

    # browser-tab and home-screen icons
    pub = os.path.join(FRONT, "public")
    shutil.copy(os.path.join(BRAND, "logo", "nexus-favicon.svg"), os.path.join(pub, "nexus.svg"))
    for src, dst in (("nexus-apple-touch-icon-180.png", "apple-touch-icon.png"), ("nexus-app-icon-192.png", "icon-192.png"),
                     ("nexus-app-icon-512.png", "icon-512.png"), ("nexus-favicon-32.png", "favicon-32.png")):
        shutil.copy(os.path.join(BRAND, "logo", "png", src), os.path.join(pub, dst))
    size = sum(os.path.getsize(os.path.join(dp, fn)) for dp, _, fns in os.walk(OUT) for fn in fns)
    print(f"frontend/src/brand: {size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
